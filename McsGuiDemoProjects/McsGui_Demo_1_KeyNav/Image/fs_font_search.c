bool fs_getCharInfo(const char c, const font_key_e font_key, fs_char_info_s *p_out_char_info)
{
    bool charInfoFound = false;
    const int32_t charIndex = fs_getCharIndex(font_key, c);
    const int32_t fontIndex = fs_getFontIndex(font_key);

    switch (font_key)
    {
        case FONT_KEY_ROBOTO_16_R_BUTTON_DARK:
        case FONT_KEY_ROBOTO_16_R_BUTTON_LIGHT:
        case FONT_KEY_ROBOTO_16_R_KEYBOARD_DARK:
        case FONT_KEY_ROBOTO_16_R_KEYBOARD_LIGHT:
        case FONT_KEY_ROBOTO_18_R_PANE_DARK:
        case FONT_KEY_ROBOTO_18_R_PANE_LIGHT:
        case FONT_KEY_ROBOTO_20_R_HEADER_DARK:
        case FONT_KEY_ROBOTO_20_R_HEADER_LIGHT:
        case FONT_KEY_ROBOTO_22_R_HEADER_DARK:
        case FONT_KEY_ROBOTO_22_R_HEADER_LIGHT:
        case FONT_KEY_ROBOTO_22_R_KEYBOARD_DARK:
        case FONT_KEY_ROBOTO_22_R_KEYBOARD_LIGHT:
        {
            if ((FS_CHAR_INFOS_IN_FONT > charIndex) && (FS_FONTS > fontIndex) && (charIndex >= 0) && (fontIndex >= 0))
            {
                *p_out_char_info = fs_char_info[fontIndex][charIndex];
                charInfoFound = true;
            }
            break;
        }
        {
            if ((FS_CHAR_INFOS_IN_DIGIT_ONLY_FONT > charIndex) && (FS_FONTS > fontIndex) && (charIndex >= 0) && (fontIndex >= 0))
            {
                *p_out_char_info = fs_char_info_digits[fontIndex][charIndex];
                charInfoFound = true;
            }
            break;
        }
        default:
            break;
    }

    return charInfoFound;
}

