static inline int32_t fs_getCharIndex(const font_key_e font_key, const char c)
{
    int32_t charIndex = -1;

    switch (font_key)
    {
        case FONT_KEY_TEXT_DARK:
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_BLUE:
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_RED:
        case FONT_KEY_TEXT_LIGHT:
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_BLUE:
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_RED:
        case FONT_KEY_TITLE_HEADER_DARK:
        case FONT_KEY_TITLE_HEADER_LIGHT:
        case FONT_KEY_TITLE_SMALL_HEADER_DARK:
        case FONT_KEY_TITLE_SMALL_HEADER_LIGHT:
            charIndex = (c - 32);
            break;
        {
            if ((c >= '0') && (c <= '9'))
            {
                charIndex = (c - '0' + 2);
            }
            else if (c == '.')
            {
                charIndex = 0;
            }
            else if (c == ',')
            {
                charIndex = 1;
            }
            else
            {
            }
            break;
        }
        default:
            break;
    }

    return charIndex;
}

static inline int32_t fs_getFontIndex(const font_key_e font_key)
{
    int32_t fontIndex = -1;

    switch (font_key)
    {
        case FONT_KEY_TEXT_DARK:
            fontIndex = 0;
            break;
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_BLUE:
            fontIndex = 1;
            break;
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_RED:
            fontIndex = 2;
            break;
        case FONT_KEY_TEXT_LIGHT:
            fontIndex = 3;
            break;
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_BLUE:
            fontIndex = 4;
            break;
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_RED:
            fontIndex = 5;
            break;
        case FONT_KEY_TITLE_HEADER_DARK:
            fontIndex = 6;
            break;
        case FONT_KEY_TITLE_HEADER_LIGHT:
            fontIndex = 7;
            break;
        case FONT_KEY_TITLE_SMALL_HEADER_DARK:
            fontIndex = 8;
            break;
        case FONT_KEY_TITLE_SMALL_HEADER_LIGHT:
            fontIndex = 9;
            break;
        default:
            break;
    }

    return fontIndex;
}


bool fs_getCharInfo(const char c, const font_key_e font_key, fs_char_info_s *p_out_char_info)
{
    bool charInfoFound = false;
    const int32_t charIndex = fs_getCharIndex(font_key, c);
    const int32_t fontIndex = fs_getFontIndex(font_key);

    switch (font_key)
    {
        case FONT_KEY_TEXT_DARK:
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_BLUE:
        case FONT_KEY_TEXT_DARK_TEXT_ACCENT_RED:
        case FONT_KEY_TEXT_LIGHT:
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_BLUE:
        case FONT_KEY_TEXT_LIGHT_TEXT_ACCENT_RED:
        case FONT_KEY_TITLE_HEADER_DARK:
        case FONT_KEY_TITLE_HEADER_LIGHT:
        case FONT_KEY_TITLE_SMALL_HEADER_DARK:
        case FONT_KEY_TITLE_SMALL_HEADER_LIGHT:
        {
            if ((FS_CHAR_INFOS_IN_FONT > charIndex) && (FS_FONTS > fontIndex) && (charIndex >= 0) && (fontIndex >= 0))
            {
                *p_out_char_info = fs_char_info[fontIndex][charIndex];
                charInfoFound = true;
            }
            break;
        }
        {
            if ((FS_CHAR_INFOS_IN_DIGIT_ONLY_FONT > charIndex) && (FS_FONTS > fontIndex) && (charIndex >= 0) && (fontIndex >= 0))
            {
                *p_out_char_info = fs_char_info_digits[fontIndex][charIndex];
                charInfoFound = true;
            }
            break;
        }
        default:
            break;
    }

    return charInfoFound;
}

